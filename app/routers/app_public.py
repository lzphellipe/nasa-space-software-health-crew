# Types accepted by POST /app/me/uploads and the extension each one is stored with.
UPLOAD_TYPES = {
    "audio/mp4": ".m4a", "audio/x-m4a": ".m4a", "audio/m4a": ".m4a", "audio/aac": ".aac", "audio/mpeg": ".mp3",
    "audio/wav": ".wav", "audio/x-wav": ".wav", "audio/webm": ".webm", "audio/ogg": ".ogg", "audio/3gpp": ".3gp",
    "image/jpeg": ".jpg", "image/png": ".png", "image/webp": ".webp", "image/heic": ".heic",
}
MEDIA_BY_EXT = {ext: mime for mime, ext in reversed(list(UPLOAD_TYPES.items()))}
UPLOAD_NAME = re.compile(r"[0-9a-f]{32}\.(m4a|aac|mp3|wav|webm|ogg|3gp|jpg|png|webp|heic)")

router = APIRouter(prefix="/api/v1/app", tags=["app: public"])


class CrewLoginIn(APIModel):
    crew_id: str = Field(min_length=1, max_length=40, examples=["ORB3-ANA"])
    pin: str = Field(min_length=1, max_length=20, examples=["2026"])


@router.post("/auth/login", summary="Sign in with Crew ID + PIN (astronauts, TEST and GROUND)")
def crew_login(body: CrewLoginIn, db: Session = Depends(get_db)):
    """Returns a 30-minute access token and a refresh token.

    Renew with `POST /api/v1/auth/refresh {"refreshToken": "..."}` (each use returns a new pair).
    `role` is `astronaut` (app screens) or `ground` (Mission Control: `/app/ground/*`).
    """
    user = db.scalar(select(User).where(User.username == body.crew_id.strip().lower()))
    if user is None or not user.active or not verify_password(body.pin, user.password_hash):
        raise HTTPException(401, "Invalid Crew ID or PIN")
    astronaut = db.get(AppAstronaut, user.astronaut_id) if user.astronaut_id else None
    if astronaut is None and user.role not in ("medical", "admin"):
        raise HTTPException(403, "This account has no CosmoMedic profile")
    pair = create_token_pair(db, user)
    db.commit()
    ground = astronaut is None
    return {"accessToken": pair.access_token, "tokenType": "bearer", "expiresIn": pair.expires_in,
            "refreshToken": pair.refresh_token, "refreshExpiresIn": pair.refresh_expires_in,
            "role": "ground" if ground else "astronaut",
            "user": {"crewId": body.crew_id.strip().upper(), "displayName": user.display_name},
            "astronaut": None if ground else {"id": astronaut.id, "name": astronaut.name, "crewId": astronaut.crew_id,
                                              "onboardingDone": astronaut.onboarding_done},
            "next": "/ground" if ground else "/home" if astronaut.onboarding_done else "/onboarding"}


@router.get("/telemetry/metrics", summary="Device metrics the API accepts, with units and quick-check thresholds")
def telemetry_metrics():
    from app.cosmo import telemetry

    return [{"metric": m.code, "label": m.label, "unit": m.unit, "min": m.lo, "max": m.hi, "becomesLog": m.log_type,
             "eva": m.eva, "quickCheck": telemetry.CHECKS[m.code][1].split(" at ")[0].replace("{v:.0f}", "…")
             .replace("{v:.1f}", "…").replace("{v:g}", "…") if m.code in telemetry.CHECKS else None} for m in telemetry.METRICS.values()]


@router.get("/foods", summary="Station food catalog (per serving), used for meal swaps")
def foods(q: str | None = Query(None, max_length=60, description="Text in the food name"),
          db: Session = Depends(get_db)):
    stmt = select(AppFood).order_by(AppFood.name)
    if q and q.strip():
        stmt = stmt.where(func.lower(AppFood.name).contains(q.strip().lower()))
    return [nutrition.food_out(f) for f in db.scalars(stmt)]


@router.get("/uploads/{name}", summary="A file sent with POST /app/me/uploads", include_in_schema=True)
def get_upload(name: str):
    # Names are random 32-hex ids generated by the API; anything else is rejected (no path traversal).
    if not UPLOAD_NAME.fullmatch(name):
        raise HTTPException(404, "File not found")
    path = get_settings().upload_dir / name
    if not path.is_file():
        raise HTTPException(404, "File not found")
    return FileResponse(path, media_type=MEDIA_BY_EXT.get(path.suffix, "application/octet-stream"))


@router.get("/mission", summary="Mission, goals and habitat modules")
def get_mission(db: Session = Depends(get_db)):
    m = logic.mission(db)
    if m is None:
        raise HTTPException(503, "CosmoMedic data not loaded")
    return views.mission_out(m, logic.today(db, m))


@router.get("/shop", summary="Shop items")
def shop(category: Literal["helmet", "suit", "pet", "window", "wall", "floor"] | None = None, db: Session = Depends(get_db)):
    stmt = select(AppShopItem).order_by(AppShopItem.category, AppShopItem.price)
    if category:
        stmt = stmt.where(AppShopItem.category == category)
    return [{"id": i.id, "category": i.category, "name": i.name, "price": i.price, "asset": i.asset}
            for i in db.scalars(stmt)]


@router.get("/leaderboard", summary="Ranking by number of logs or by coins")
def leaderboard(by: Literal["logs", "coins"] = "logs", user: User = Depends(get_current_user), db: Session = Depends(get_db)):
    return {"by": by, "note": "Daily logs: one point per saved log. Coins: +10 per log, minus purchases.",
            "ranking": views.leaderboard(db, by, user.astronaut_id)}
