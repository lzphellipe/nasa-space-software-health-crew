def for_path(path: str) -> list[str]:
    for prefix, values in ROUTES:
        if path == prefix or path.startswith(prefix + "/") or path.startswith(prefix + "?"):
            return values
    return []


def checkin_provenance(source: str) -> str:
    return SIMULATED if source == "synthetic" else USER


def support_provenance(reason: str) -> str:
    """Requests the astronaut made (or symptoms they reported) vs ones opened by the rules."""
    return DERIVED if reason == "pattern" else USER
